import uuid
from datetime import datetime

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    ForeignKey,
    ForeignKeyConstraint,
    Index,
    String,
    Text,
    Uuid,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.database.base import Base


class CAPARecommendation(Base):
    """
    A corrective or preventive action recommendation.

    Generated by AI from confirmed or supported hypotheses,
    subject to human review before implementation.
    """

    __tablename__ = "capa_recommendations"

    __table_args__ = (
        CheckConstraint(
            """
            capa_type IN (
                'corrective',
                'preventive'
            )
            """,
            name="valid_capa_type",
        ),
        CheckConstraint(
            """
            priority IN (
                'low',
                'medium',
                'high',
                'critical'
            )
            """,
            name="valid_capa_priority",
        ),
        CheckConstraint(
            """
            status IN (
                'proposed',
                'approved',
                'in_progress',
                'completed',
                'rejected'
            )
            """,
            name="valid_capa_status",
        ),
        ForeignKeyConstraint(
            ["hypothesis_id", "investigation_id"],
            [
                "rca_hypotheses.id",
                "rca_hypotheses.investigation_id",
            ],
            ondelete="CASCADE",
        ),
        Index(
            "ix_capa_investigation_status",
            "investigation_id",
            "status",
        ),
        Index(
            "ix_capa_hypothesis",
            "hypothesis_id",
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    investigation_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey(
            "investigations.id",
            ondelete="CASCADE",
        ),
        nullable=False,
    )

    hypothesis_id: Mapped[uuid.UUID] = mapped_column(
        Uuid(as_uuid=True),
        nullable=False,
    )

    capa_type: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
    )

    title: Mapped[str] = mapped_column(
        String(300),
        nullable=False,
    )

    description: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )

    expected_outcome: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    verification_method: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    effectiveness_criteria: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    priority: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default="medium",
        server_default="medium",
    )

    residual_risk: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    status: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
        default="proposed",
        server_default="proposed",
    )

    review_note: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )
